"""Grounded recovery advice tool."""

from __future__ import annotations

from typing import Any, Dict, List

from nurse.schemas import VerifiedRCLContext
from nurse_agent.llm_client import OpenAICompatibleClient


def _signal_hint(signal: str) -> str:
    text = signal.lower()
    if "cpu" in text:
        return "Check CPU saturation, throttling, noisy neighbors, and restart or reschedule the affected workload only after confirming impact."
    if "mem" in text or "memory" in text:
        return "Check memory pressure, leaks, and OOM events; consider rolling restart or increasing limits after validation."
    if "latency" in text or "duration" in text:
        return "Inspect slow dependency calls and recent traffic changes before mitigation."
    if "error" in text or "exception" in text:
        return "Inspect recent errors, deployments, and dependency failures before rollback or restart."
    return "Validate the top candidate with the cited evidence and choose the least disruptive mitigation first."


def _llm_prompt(context: VerifiedRCLContext, top: str, evidence_ids: List[str]) -> str:
    evidence_lines = []
    for item in context.evidence_summaries[:12]:
        evidence_lines.append(
            f"- {item.get('evidence_id')}: entity={item.get('entity')} signal={item.get('signal')} kind={item.get('kind')} role={item.get('metric_role', '')}"
        )
    path_lines = []
    for item in context.closure_paths[:8]:
        path_lines.append(str(item))
    return "\n".join(
        [
            "You are the NURSE User Manager. Give concise SRE recovery advice only from the verified context.",
            f"Dataset: {context.dataset}",
            f"Case: {context.case_id}",
            f"Top candidate: {top}",
            f"Supporting evidence IDs: {', '.join(evidence_ids)}",
            "Verified evidence:",
            *evidence_lines,
            "Evidence paths:",
            *path_lines,
            "Return one short paragraph. Do not invent evidence IDs or unobserved causal links.",
        ]
    )


def run(payload: Dict[str, Any]) -> Dict[str, Any]:
    context = VerifiedRCLContext.from_dict(dict(payload["context"]))
    top = context.ranked_candidates[0] if context.ranked_candidates else ""
    supporting_ids = context.evidence_ids.get(top, [])[:5] if top else []
    summaries = [
        item for item in context.evidence_summaries if item.get("evidence_id") in supporting_ids
    ]
    signal = str(summaries[0].get("signal") if summaries else "")
    rationale_ids = ", ".join(supporting_ids) if supporting_ids else "verified evidence graph"
    llm_explanation = ""
    if bool(payload.get("use_llm", False)):
        client = OpenAICompatibleClient(model=str(payload.get("model") or "gpt-5-nano"))
        llm_explanation = client.complete_text(
            _llm_prompt(context, top, supporting_ids),
            max_output_tokens=int(payload.get("max_output_tokens", 2048)),
        ).strip()
    advice: List[Dict[str, Any]] = [
        {
            "priority": "high",
            "action": f"Verify `{top}` first and apply targeted mitigation only if the cited signals reproduce.",
            "rationale": f"NURSE ranks `{top}` highest using grounded evidence IDs: {rationale_ids}.",
            "risk": "Mitigating without confirmation may disturb a downstream symptom rather than the source service.",
            "verification_before_action": f"Re-check telemetry and logs for `{top}` in the benchmark fault window.",
        }
    ]
    if top:
        advice.append(
            {
                "priority": "medium",
                "action": _signal_hint(signal),
                "rationale": f"The recommendation is derived from the dominant verified signal `{signal or 'unknown'}` for `{top}`.",
                "risk": "Operational changes should follow local SRE runbooks and change-control policy.",
                "verification_before_action": "Confirm the same signal is still active and is not explained by a known maintenance event.",
            }
        )
    if llm_explanation:
        advice.append(
            {
                "priority": "medium",
                "action": llm_explanation,
                "rationale": "Generated by the LLM User Manager from the Verified RCL Context; ranking was not modified.",
                "risk": "Treat this as grounded operator guidance, not an automatic remediation command.",
                "verification_before_action": "Check that all referenced evidence IDs exist in the report before acting.",
            }
        )
    return {
        "dataset": context.dataset,
        "case_id": context.case_id,
        "recovery_advice": advice,
        "llm_explanation": llm_explanation,
    }

